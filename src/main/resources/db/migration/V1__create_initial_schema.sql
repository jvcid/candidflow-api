CREATE TABLE candidates (
    id NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR2(120 CHAR) NOT NULL,
    email VARCHAR2(180 CHAR) NOT NULL,
    phone VARCHAR2(30 CHAR),
    linkedin_url VARCHAR2(500 CHAR),
    github_url VARCHAR2(500 CHAR),
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_candidates PRIMARY KEY (id),
    CONSTRAINT uk_candidates_email UNIQUE (email)
);

CREATE TABLE jobs (
    id NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR2(150 CHAR) NOT NULL,
    company VARCHAR2(150 CHAR) NOT NULL,
    description CLOB NOT NULL,
    requirements CLOB,
    location VARCHAR2(150 CHAR),
    work_model VARCHAR2(20 CHAR) NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT ck_jobs_work_model CHECK (work_model IN ('REMOTE', 'HYBRID', 'ON_SITE')),
    CONSTRAINT ck_jobs_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE applications (
    id NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    candidate_id NUMBER(19, 0) NOT NULL,
    job_id NUMBER(19, 0) NOT NULL,
    cover_letter CLOB,
    status VARCHAR2(30 CHAR) DEFAULT 'SUBMITTED' NOT NULL,
    applied_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT uk_applications_candidate_job UNIQUE (candidate_id, job_id),
    CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_id) REFERENCES candidates (id),
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT ck_applications_status CHECK (
        status IN ('SUBMITTED', 'UNDER_REVIEW', 'INTERVIEW', 'APPROVED', 'REJECTED', 'WITHDRAWN')
    )
);

CREATE TABLE feedbacks (
    id NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    application_id NUMBER(19, 0) NOT NULL,
    content CLOB NOT NULL,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_feedbacks PRIMARY KEY (id),
    CONSTRAINT fk_feedbacks_application
        FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_jobs_status ON jobs (status);
CREATE INDEX idx_jobs_work_model ON jobs (work_model);
CREATE INDEX idx_applications_job ON applications (job_id);
CREATE INDEX idx_applications_status ON applications (status);
CREATE INDEX idx_feedbacks_application ON feedbacks (application_id);
